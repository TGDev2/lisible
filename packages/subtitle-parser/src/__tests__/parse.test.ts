import { describe, it, expect } from 'vitest';
import { detectFormat, parseSubtitle, validateSubtitle, parseByFormat } from '../parse';

describe('detectFormat', () => {
  it('should detect VTT format from WEBVTT header', () => {
    expect(detectFormat('WEBVTT\n\n00:00:01.000 --> 00:00:04.000\nHello')).toBe('vtt');
  });

  it('should detect VTT format with metadata', () => {
    expect(detectFormat('WEBVTT Kind: captions\n\n00:00:01.000 --> 00:00:04.000\nHello')).toBe('vtt');
  });

  it('should detect SRT format from sequence number', () => {
    expect(detectFormat('1\n00:00:01,000 --> 00:00:04,000\nHello')).toBe('srt');
  });

  it('should detect SRT from timecode with comma', () => {
    expect(detectFormat('1\n00:00:01,500 --> 00:00:04,000\nHello')).toBe('srt');
  });

  it('should handle BOM in VTT', () => {
    expect(detectFormat('\uFEFFWEBVTT\n\n00:00:01.000 --> 00:00:04.000\nHello')).toBe('vtt');
  });

  it('should handle BOM in SRT', () => {
    expect(detectFormat('\uFEFF1\n00:00:01,000 --> 00:00:04,000\nHello')).toBe('srt');
  });

  it('should handle leading empty lines', () => {
    expect(detectFormat('\n\n1\n00:00:01,000 --> 00:00:04,000\nHello')).toBe('srt');
  });

  it('should return null for unrecognized format', () => {
    expect(detectFormat('random text\nno timecodes here')).toBeNull();
  });

  it('should return null for empty content', () => {
    expect(detectFormat('')).toBeNull();
  });
});

describe('parseSubtitle', () => {
  it('should auto-detect and parse SRT', () => {
    const content = `1
00:00:01,000 --> 00:00:04,000
Hello world`;

    const result = parseSubtitle(content);

    expect(result.format).toBe('srt');
    expect(result.segments).toHaveLength(1);
    expect(result.errors).toHaveLength(0);
  });

  it('should auto-detect and parse VTT', () => {
    const content = `WEBVTT

00:00:01.000 --> 00:00:04.000
Hello world`;

    const result = parseSubtitle(content);

    expect(result.format).toBe('vtt');
    expect(result.segments).toHaveLength(1);
    expect(result.errors).toHaveLength(0);
  });

  it('should return error for unknown format', () => {
    const content = `random text
no valid subtitles`;

    const result = parseSubtitle(content);

    expect(result.errors.length).toBeGreaterThan(0);
    expect(result.segments).toHaveLength(0);
  });

  it('should parse complex SRT file', () => {
    const content = `1
00:00:01,000 --> 00:00:04,000
[FORMATEUR] Bonjour à tous

2
00:00:05,000 --> 00:00:08,000
[Musique]

3
00:00:09,000 --> 00:00:12,500
Bienvenue dans cette formation
sur le développement web`;

    const result = parseSubtitle(content);

    expect(result.format).toBe('srt');
    expect(result.segments).toHaveLength(3);
    expect(result.segments[0].speaker).toBe('[FORMATEUR]');
    expect(result.segments[1].isSoundInfo).toBe(true);
    expect(result.segments[2].text).toContain('\n');
  });

  it('should parse complex VTT file', () => {
    const content = `WEBVTT
Kind: captions
Language: fr

NOTE
Generated by SME Studio

1
00:00:01.000 --> 00:00:04.000
[NARRATEUR] Il était une fois

STYLE
::cue { color: white; }

2
00:00:05.000 --> 00:00:08.000 align:center
Dans un pays lointain`;

    const result = parseSubtitle(content);

    expect(result.format).toBe('vtt');
    expect(result.segments).toHaveLength(2);
    expect(result.segments[0].speaker).toBe('[NARRATEUR]');
  });
});

describe('parseByFormat', () => {
  it('should parse as SRT when specified', () => {
    const content = `1
00:00:01,000 --> 00:00:04,000
Hello world`;

    const result = parseByFormat(content, 'srt');

    expect(result.format).toBe('srt');
    expect(result.segments).toHaveLength(1);
  });

  it('should parse as VTT when specified', () => {
    const content = `WEBVTT

00:00:01.000 --> 00:00:04.000
Hello world`;

    const result = parseByFormat(content, 'vtt');

    expect(result.format).toBe('vtt');
    expect(result.segments).toHaveLength(1);
  });

  it('should force format even if content suggests otherwise', () => {
    // This is SRT content but we force VTT parsing
    const content = `1
00:00:01,000 --> 00:00:04,000
Hello world`;

    const result = parseByFormat(content, 'vtt');

    // Should try to parse as VTT (will fail on WEBVTT header check)
    expect(result.format).toBe('vtt');
    expect(result.errors.length).toBeGreaterThan(0);
  });
});

describe('validateSubtitle', () => {
  it('should validate correct SRT file', () => {
    const content = `1
00:00:01,000 --> 00:00:04,000
Hello world`;

    const result = validateSubtitle(content);

    expect(result.isValid).toBe(true);
    expect(result.format).toBe('srt');
    expect(result.errors).toHaveLength(0);
  });

  it('should validate correct VTT file', () => {
    const content = `WEBVTT

00:00:01.000 --> 00:00:04.000
Hello world`;

    const result = validateSubtitle(content);

    expect(result.isValid).toBe(true);
    expect(result.format).toBe('vtt');
    expect(result.errors).toHaveLength(0);
  });

  it('should invalidate unrecognized format', () => {
    const content = `random text`;

    const result = validateSubtitle(content);

    expect(result.isValid).toBe(false);
    expect(result.format).toBeNull();
  });

  it('should invalidate SRT with errors', () => {
    const content = `abc
invalid timecode
Hello world`;

    const result = validateSubtitle(content);

    expect(result.isValid).toBe(false);
    expect(result.errors.length).toBeGreaterThan(0);
  });

  it('should invalidate empty file', () => {
    const result = validateSubtitle('');

    expect(result.isValid).toBe(false);
  });

  it('should invalidate VTT without WEBVTT header', () => {
    const content = `00:00:01.000 --> 00:00:04.000
Hello world`;

    const result = validateSubtitle(content);

    // This will be detected as SRT (starts with timecode-like content)
    // and fail because it's not valid SRT format
    expect(result.isValid).toBe(false);
  });
});

describe('integration tests', () => {
  it('should correctly extract all timecodes as milliseconds', () => {
    const content = `1
00:00:01,500 --> 00:00:04,750
First

2
01:30:00,000 --> 01:30:05,250
Second`;

    const result = parseSubtitle(content);

    expect(result.segments[0].startMs).toBe(1500);
    expect(result.segments[0].endMs).toBe(4750);
    expect(result.segments[1].startMs).toBe(5400000); // 1h 30m = 5400000ms
    expect(result.segments[1].endMs).toBe(5405250);
  });

  it('should handle real-world e-learning subtitle file', () => {
    const content = `1
00:00:00,500 --> 00:00:03,000
[FORMATEUR] Bonjour et bienvenue dans ce module.

2
00:00:03,500 --> 00:00:07,000
Aujourd'hui, nous allons aborder
les fondamentaux du JavaScript.

3
00:00:08,000 --> 00:00:10,500
[Musique de transition]

4
00:00:11,000 --> 00:00:15,500
Commençons par les variables.
Il existe trois mots-clés : var, let et const.`;

    const result = parseSubtitle(content);

    expect(result.format).toBe('srt');
    expect(result.errors).toHaveLength(0);
    expect(result.segments).toHaveLength(4);

    expect(result.segments[0].speaker).toBe('[FORMATEUR]');
    expect(result.segments[2].isSoundInfo).toBe(true);
    expect(result.segments[3].text).toContain('var, let et const');
  });
});
